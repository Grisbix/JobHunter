"""Lever, Ashby and Greenhouse company directories: from a name to a feed to follow.

Part of jobhunter.sources. To follow a company through the public API of its recruiting
tool, the identifier of its job board is needed (`jobs.lever.co/<id>`). The Companies
panel finds it here from the typed name, without going on the web.

Data: `directories/*.json`, 3,600 companies taken from jobsync (MIT licence,
`directories/LICENSE-jobsync.txt`), regenerated by `tools/directories.py`. The Lever
region (lever.co or eu.lever.co) is resolved at collection time (sources.ats).

Plus the companies career-ops tracks (MIT licence, `directories/LICENSE-career-ops.txt`),
`career-ops.json`, which may name other tools (Recruitee, Workable…): `SUIVABLES`.

Workday has no such list to borrow: each installation builds its own from Common
Crawl (`sources.discovery`, `workday_directory.json` next to the queue), searched here
too when present. Its identifier is `tenant.wd3/site`.
"""

import functools
import json
import unicodedata
from dataclasses import dataclass
from importlib import resources
from typing import Any

OUTILS = ("lever", "ashby", "greenhouse")
# Every tool a directory entry may name and `inventory.ajouter_flux` can follow.
SUIVABLES = (
    *OUTILS,
    "recruitee",
    "smartrecruiters",
    "teamtailor",
    "workable",
    "personio",
    "breezy",
)


@dataclass(frozen=True)
class Entree:
    """A company of the directory."""

    nom: str
    outil: str  # "lever", "ashby" or "greenhouse"
    jeton: str  # the identifier of the job board


def _plat(texte: str) -> str:
    """Minuscules, sans accents ni ponctuation : « L'Oréal » → « loreal »."""
    t = unicodedata.normalize("NFKD", texte.casefold())
    return "".join(c for c in t if c.isalnum())


@functools.cache
def entrees() -> tuple[Entree, ...]:
    """All the companies of the three directories (read once)."""
    sortie: list[Entree] = []
    for outil in OUTILS:
        brut = (
            resources.files(__package__)
            .joinpath("directories", f"{outil}.json")
            .read_text(encoding="utf-8")
        )
        sortie.extend(Entree(nom, outil, jeton) for nom, jeton in json.loads(brut))
    brut = (
        resources.files(__package__)
        .joinpath("directories", "career-ops.json")
        .read_text(encoding="utf-8")
    )
    deja = {(e.outil, e.jeton.lower()) for e in sortie}
    sortie.extend(
        Entree(nom, outil, jeton)
        for nom, outil, jeton in json.loads(brut)
        if outil in SUIVABLES and (outil, jeton.lower()) not in deja
    )
    return tuple(sortie)


_LOCALES: dict[str, Any] = {"cle": None, "entrees": ()}


def entrees_workday() -> tuple[Entree, ...]:
    """The user's Workday directory, if built (read again when the file changes)."""
    from jobhunter import inventory
    from jobhunter.sources import discovery

    f = discovery.chemin_annuaire()
    try:
        cle = (str(f), f.stat().st_mtime_ns)
    except OSError:
        return ()
    if _LOCALES["cle"] != cle:
        sites = discovery.charger_annuaire()["sites"]
        _LOCALES["entrees"] = tuple(
            Entree(inventory._nom_de_slug(t), "workday", f"{t}.{wd}/{site}")
            for t, wd, site in sites
        )
        _LOCALES["cle"] = cle
    return tuple(_LOCALES["entrees"])


def workday_de_jeton(jeton: str) -> tuple[str, str, str] | None:
    """« tenant.wd3/site » → (tenant, "wd3", site); None if it is not one."""
    import re

    m = re.fullmatch(r"([a-z0-9-]+)\.(wd\d+)/([A-Za-z0-9_-]+)", str(jeton or ""))
    return (m.group(1), m.group(2), m.group(3)) if m else None


def chercher(texte: str, limite: int = 30) -> list[Entree]:
    """The companies whose name (or identifier) matches `texte`.

    Order: exact name, then name starting with the text, then a word of the name
    starting with it, then the text inside a word; on a tie, by name.

    Args:
        texte: what the user typed; fewer than 2 useful characters → [].
        limite: maximum number of results.
    """
    q = _plat(texte)
    if len(q) < 2:
        return []
    classees = []
    for e in (*entrees(), *entrees_workday()):
        nom, jeton = _plat(e.nom), _plat(e.jeton)
        mots = [_plat(m) for m in e.nom.split()]
        if q in (nom, jeton):
            rang = 0
        elif nom.startswith(q) or jeton.startswith(q):
            rang = 1
        elif any(m.startswith(q) for m in mots):
            rang = 2
        elif any(q in m for m in mots):
            rang = 3
        else:
            continue
        classees.append((rang, e.nom.casefold(), e.outil, e))
    classees.sort(key=lambda x: x[:3])
    return [e for *_, e in classees[:limite]]
